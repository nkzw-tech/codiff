import { flagDefinitions } from './arguments.js';

export const completionShells = ['bash', 'fish', 'zsh'];

// Git refs are the most common first argument, so every shell offers them.
const refCommand =
  "git for-each-ref --format='%(refname:short)' refs/heads refs/remotes refs/tags 2>/dev/null";

// What a flag's value should complete to is derived from the placeholder shown
// in `codiff --help`, so a new flag is covered without touching this file:
// `<a|b|c>` completes the listed values, `<ref>` completes git refs, `<file>`
// completes paths, and anything else (`<id>`) completes nothing.
const getValueCompletion = (argument) => {
  if (!argument) {
    return null;
  }
  const placeholder = argument.replace(/^<|>$/g, '');
  if (placeholder.includes('|')) {
    return { type: 'values', values: placeholder.split('|').sort() };
  }
  return placeholder === 'ref' || placeholder === 'file' ? { type: placeholder } : { type: 'none' };
};

const visibleFlags = () =>
  flagDefinitions
    .filter(({ hidden }) => !hidden)
    .map((flag) => ({ ...flag, completion: getValueCompletion(flag.argument) }));

const quote = (text) => `'${text.replaceAll("'", String.raw`'\''`)}'`;

export const generateCompletionScript = (shell) => {
  if (shell === 'bash') {
    return generateBashCompletions();
  }
  if (shell === 'fish') {
    return generateFishCompletions();
  }
  if (shell === 'zsh') {
    return generateZshCompletions();
  }
  throw new Error(
    `Unsupported shell for completions: ${shell}. Supported shells: ${completionShells.join(', ')}.`,
  );
};

const header = (shell) =>
  `# codiff completions for ${shell}. Generated by \`codiff --completions ${shell}\`.`;

function generateBashCompletions() {
  const flags = visibleFlags();
  const spellings = (candidates) =>
    candidates.flatMap(({ name, short }) => [`--${name}`, ...(short ? [`-${short}`] : [])]);
  const withCompletion = (type) => flags.filter(({ completion }) => completion?.type === type);
  const takingValue = spellings(flags.filter(({ completion }) => completion));
  const sourceFlags = flags
    .filter(({ consumesSource }) => consumesSource)
    .flatMap(({ name }) => [`--${name}`, `--${name}=*`]);

  // `-o default` fills an empty candidate list with file names, which is right
  // for a path and misleading for a ref, a session id or a mistyped flag.
  const noFileFallback = 'compopt +o default 2>/dev/null';
  const cases = [
    ...withCompletion('values').map(({ completion, name }) => ({
      body: [
        `COMPREPLY=($(compgen -W ${quote(completion.values.join(' '))} -- "$current"))`,
        noFileFallback,
      ],
      patterns: [`--${name}`],
    })),
    {
      body: ['_codiff_complete_refs "$current"', noFileFallback],
      patterns: spellings(withCompletion('ref')),
    },
    { body: ['COMPREPLY=()'], patterns: spellings(withCompletion('file')) },
    { body: ['COMPREPLY=()', noFileFallback], patterns: spellings(withCompletion('none')) },
  ].filter(({ patterns }) => patterns.length);

  const renderCase = ({ body, patterns }) =>
    [
      `    ${patterns.join('|')})`,
      ...[...body, 'return 0'].map((line) => `      ${line}`),
      '      ;;',
    ].join('\n');

  return `${header('bash')}

_codiff_refs() {
  ${refCommand}
}

# Ref names are attacker-controlled in a cloned repository and may contain
# \`$(...)\`, backticks or other metacharacters. \`compgen -W\` expands the words it
# is given, so refs are matched here as plain data and handed back quoted.
_codiff_complete_refs() {
  local candidate ref
  COMPREPLY=()
  while IFS= read -r ref; do
    printf -v candidate '%q' "$ref"
    # A word that needs quoting reaches the completion already escaped, so the
    # typed prefix is compared against both spellings of the ref.
    if [[ "$ref" == "$1"* || "$candidate" == "$1"* ]]; then
      COMPREPLY+=("$candidate")
    fi
  done < <(_codiff_refs)
}

# Whether the ref has already been given, either as an argument or through a
# flag such as ${sourceFlags.join(' or ')}. Once it has, the only argument left
# is the repository path.
_codiff_has_source() {
  local index=1 word
  while [ "$index" -lt "$COMP_CWORD" ]; do
    word="\${COMP_WORDS[index]}"
    case "$word" in
      ${sourceFlags.join('|')})
        return 0
        ;;
      ${takingValue.join('|')})
        index=$((index + 1))
        if [ "\${COMP_WORDS[index]}" = '=' ]; then
          index=$((index + 1))
        fi
        ;;
      -*|=) ;;
      *) return 0 ;;
    esac
    index=$((index + 1))
  done
  return 1
}

_codiff() {
  local current flag
  current="\${COMP_WORDS[COMP_CWORD]}"
  flag="\${COMP_WORDS[COMP_CWORD - 1]}"
  # \`=\` is one of bash's word break characters, so \`--agent=codex\` arrives as
  # three words and the flag is two words back.
  if [[ "$flag" == '=' && $COMP_CWORD -ge 2 ]]; then
    flag="\${COMP_WORDS[COMP_CWORD - 2]}"
  fi

  case "$flag" in
${cases.map(renderCase).join('\n')}
  esac

  if [[ "$current" == -* ]]; then
    COMPREPLY=($(compgen -W ${quote(spellings(flags).join(' '))} -- "$current"))
    ${noFileFallback}
    return 0
  fi

  # \`codiff [<ref>] [path]\`: only a path can follow the ref, and an empty
  # candidate list hands the word to the shell's own path completion.
  if _codiff_has_source; then
    COMPREPLY=()
    return 0
  fi

  _codiff_complete_refs "$current"
}

complete -o bashdefault -o default -F _codiff codiff
`;
}

function generateFishCompletions() {
  const flags = visibleFlags();
  const sourceFlags = flags
    .filter(({ consumesSource }) => consumesSource)
    .flatMap(({ name }) => [`--${name}`, `'--${name}=*'`])
    .join(' ');
  const valueFlags = flags
    .filter(({ completion }) => completion)
    .map(({ name }) => `--${name}`)
    .join(' ');
  // Fish keeps file completion on for the command so the trailing `[path]`
  // argument still completes; flags opt out of it individually.
  const lines = flags.map(({ completion, description, name, short }) => {
    const parts = ['complete -c codiff', ...(short ? [`-s ${short}`] : []), `-l ${name}`];
    if (completion?.type === 'values') {
      parts.push(`-x -a ${quote(completion.values.join(' '))}`);
    } else if (completion?.type === 'ref') {
      parts.push("-x -a '(__codiff_refs)'");
    } else if (completion?.type === 'file') {
      parts.push('-r -F');
    } else if (completion) {
      parts.push('-x');
    }
    if (description) {
      parts.push(`-d ${quote(description)}`);
    }
    return parts.join(' ');
  });

  return `${header('fish')}

function __codiff_refs
    command ${refCommand}
end

# The ref is only completable while it is still the argument being typed: once it
# is given, as a word or through a flag, the repository path is all that is left.
function __codiff_expects_ref
    set -l tokens (commandline --current-process --tokens-expanded --cut-at-cursor)
    set -e tokens[1]
    set -l skip 0
    for token in $tokens
        if test $skip -eq 1
            set skip 0
            continue
        end
        switch $token
            case ${sourceFlags}
                return 1
            case ${valueFlags}
                set skip 1
            case '-*'
            case '*'
                return 1
        end
    end
    return 0
end

complete -c codiff -n __codiff_expects_ref -a '(__codiff_refs)' -d 'Git ref'
${lines.join('\n')}
`;
}

function generateZshCompletions() {
  const flags = visibleFlags();
  const sourceFlags = flags
    .filter(({ consumesSource }) => consumesSource)
    .flatMap(({ name }) => [`--${name}`, `--${name}=*`])
    .join('|');
  const escape = (text) =>
    text.replaceAll("'", String.raw`'\''`).replaceAll(/[[\]:]/g, String.raw`\$&`);
  const argumentSpecifications = flags.map(({ completion, description, name, short }) => {
    const flag = short ? `'(-${short} --${name})'{-${short},--${name}}'` : `'(--${name})--${name}`;
    const value =
      completion?.type === 'values'
        ? `:${name}:(${completion.values.join(' ')})`
        : completion?.type === 'ref'
          ? ':ref:__codiff_refs'
          : completion?.type === 'file'
            ? ':file:_files'
            : completion
              ? `:${name}:`
              : '';
    return `    ${flag}[${escape(description ?? '')}]${value}' \\`;
  });

  return `${header('zsh')}
#compdef codiff

__codiff_refs() {
  local -a refs
  refs=(\${(f)"$(${refCommand})"})
  _describe -t refs 'ref' refs
}

_codiff() {
  _arguments -s \\
${argumentSpecifications.join('\n')}
    '1:ref or path:__codiff_target' \\
    '*:path:_files'
}

# The ref is only completable while it is still the argument being typed: once it
# is given, as a word or through a flag, the repository path is all that is left.
__codiff_target() {
  if (( \${words[(I)(${sourceFlags})]} )); then
    _files
    return
  fi
  _alternative 'refs:ref:__codiff_refs' 'files:file:_files'
}

if [ "\${funcstack[1]}" = '_codiff' ]; then
  _codiff "$@"
else
  compdef _codiff codiff
fi
`;
}
